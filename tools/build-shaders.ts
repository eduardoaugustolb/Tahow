import { copyFileSync, readdirSync, statSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
import { buildWidgets } from './build-widgets';

process.chdir(resolve(import.meta.dir, '..'));

const glassShader = 'shell/shaders/frosted_glass.frag';
for (const dir of ['shell/lock', 'integrations/ryostore/lockscreen/content', 'integrations/widgets/content']) {
  copyFileSync(glassShader, `${dir}/shaders/frosted_glass.frag`);
}

const qsb = Bun.which('qsb') || '/usr/lib/qt6/bin/qsb';
let count = 0;
function walk(dir: string) {
  for (const name of readdirSync(dir)) {
    const path = `${dir}/${name}`;
    if (path === 'integrations/ryostore/widgets') continue; // Generated by build-widgets.
    if (statSync(path).isDirectory()) walk(path);
    else if (name.endsWith('.frag')) { execFileSync(qsb, ['--qt6', '-o', `${path}.qsb`, path]); count++; }
  }
}
walk('shell'); walk('integrations');
buildWidgets();
console.log(`Built ${count} Qt 6 shaders`);
