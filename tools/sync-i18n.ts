// Run with bun tools/sync-i18n.ts [--check]. JSON catalogs are canonical.
import { resolve } from 'node:path';
const root = resolve(import.meta.dir, '..');
const check = process.argv.includes('--check');
const catalogs: Record<string, Record<string, string>> = {};
for (const code of ['en-US', 'pt-BR']) {
    const input = await Bun.file(`${root}/locales/${code}.json`).json();
    for (const [key, value] of Object.entries(input)) {
        if (typeof value !== 'string' || !key) throw new Error(`${code}: invalid entry ${key}`);
    }
    catalogs[code] = Object.fromEntries(Object.entries(input).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) as Record<string, string>;
}
if (JSON.stringify(Object.keys(catalogs['en-US'])) !== JSON.stringify(Object.keys(catalogs['pt-BR']))) throw new Error('Catalog keys differ');
const generated = '.pragma library\n// Generated by bun tools/sync-i18n.ts. Edit locales/*.json.\nvar catalogs = ' + JSON.stringify(catalogs, null, 2) + ';\n';
const lock = 'integrations/ryostore/lockscreen/content/i18n';
const targets = new Map<string, string>([
    ['shell/lib/messages.js', generated],
    [`${lock}/messages.js`, generated],
    [`${lock}/locale.js`, await Bun.file(`${root}/shell/lib/locale.js`).text()],
    [`${lock}/paths.js`, await Bun.file(`${root}/shell/lib/paths.js`).text()],
    [`${lock}/material.js`, await Bun.file(`${root}/shell/lib/material.js`).text()],
]);
for (const [path, content] of targets) {
    if (check) {
        if (!await Bun.file(`${root}/${path}`).exists() || await Bun.file(`${root}/${path}`).text() !== content) throw new Error(`Outdated generated file: ${path}`);
    } else await Bun.write(`${root}/${path}`, content);
}
console.log(check ? 'i18n generated files are current' : 'i18n generated files updated');
